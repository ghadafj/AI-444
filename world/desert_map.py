"""
The desert map: the world the rescue drone flies over.

PROVIDED CODE - do not edit this file.

A map is a grid of cells. A cell is a (row, col) tuple. Row 0 is the top row.

Terrain (what the drone knows from satellite images):
    '.'  sand       cost 1 to enter   camera finds the hiker 90% of the time
    'r'  rocks      cost 2 to enter   camera finds the hiker 70% of the time
    'd'  dunes      cost 3 to enter   camera finds the hiker 50% of the time
    '#'  mountain   the drone cannot fly through it

Hidden things (the drone does NOT know them at the start):
    sandstorms  flying into a sandstorm cell destroys the drone.
                Every cell next to a sandstorm (up, down, left, right) has dust in the air.
    hiker       the lost person. Sits on one passable cell.

Known special places:
    base         where the drone starts, keeps the medical kit, and can refuel
    oasis        a village well: water bottles and a fuel station
    last_signal  where the hiker's phone sent its last signal
"""

from __future__ import annotations

import math
import random
from typing import Dict, Iterable, List, Optional, Tuple

Cell = Tuple[int, int]

SAND, ROCK, DUNE, MOUNTAIN = ".", "r", "d", "#"

TERRAIN_COST = {SAND: 1, ROCK: 2, DUNE: 3}
DETECT_PROB = {SAND: 0.9, ROCK: 0.7, DUNE: 0.5}
TERRAIN_NAME = {SAND: "sand", ROCK: "rocks", DUNE: "dunes", MOUNTAIN: "mountain"}

# Neighbour order is fixed (up, right, down, left) so every run is reproducible.
MOVES = [(-1, 0), (0, 1), (1, 0), (0, -1)]

# How fast the hiker prior fades with distance from the last phone signal.
PRIOR_SPREAD = 3.0


class DesertMap:
    """A desert grid with terrain, special places and hidden dangers."""

    def __init__(self, grid: List[str], base: Cell, oasis: Cell,
                 storms: Iterable[Cell] = (), hiker: Optional[Cell] = None,
                 last_signal: Optional[Cell] = None, seed: Optional[int] = None):
        self.grid = [list(row) for row in grid]
        self.rows = len(self.grid)
        self.cols = len(self.grid[0])
        self.base = base
        self.oasis = oasis
        self.storms = frozenset(storms)
        self.hiker = hiker
        self.last_signal = last_signal if last_signal is not None else base
        self.seed = seed

    # ------------------------------------------------------------------ terrain
    def in_bounds(self, cell: Cell) -> bool:
        r, c = cell
        return 0 <= r < self.rows and 0 <= c < self.cols

    def terrain(self, cell: Cell) -> str:
        r, c = cell
        return self.grid[r][c]

    def passable(self, cell: Cell) -> bool:
        return self.in_bounds(cell) and self.terrain(cell) != MOUNTAIN

    def cost(self, cell: Cell) -> int:
        """Cost to ENTER this cell (fuel used by the drone)."""
        return TERRAIN_COST[self.terrain(cell)]

    def detect_prob(self, cell: Cell) -> float:
        """P(camera sees the hiker | hiker is in this cell)."""
        return DETECT_PROB[self.terrain(cell)]

    def neighbors(self, cell: Cell) -> List[Cell]:
        """Passable cells up, right, down, left of `cell` (in that order)."""
        r, c = cell
        out = []
        for dr, dc in MOVES:
            n = (r + dr, c + dc)
            if self.passable(n):
                out.append(n)
        return out

    def passable_cells(self) -> List[Cell]:
        return [(r, c) for r in range(self.rows) for c in range(self.cols)
                if self.grid[r][c] != MOUNTAIN]

    # ------------------------------------------------------------------ sensors
    def has_dust(self, cell: Cell) -> bool:
        """Dust sensor: True if a sandstorm is in a neighbouring cell."""
        return any(n in self.storms for n in self.neighbors(cell))

    def hiker_prior(self) -> Dict[Cell, float]:
        """Starting belief about where the hiker is (sums to 1).

        People rarely walk far from where their phone last worked, so the
        prior falls off with distance from `last_signal`. Mountains get 0.
        """
        lr, lc = self.last_signal
        weights = {}
        for cell in self.passable_cells():
            d = math.hypot(cell[0] - lr, cell[1] - lc)
            weights[cell] = math.exp(-d / PRIOR_SPREAD)
        total = sum(weights.values())
        return {cell: w / total for cell, w in weights.items()}

    # ------------------------------------------------------------------ display
    def to_ascii(self, marks: Optional[Dict[Cell, str]] = None, reveal: bool = False) -> str:
        """Text picture of the map. `marks` overrides single cells."""
        marks = marks or {}
        lines = ["    " + "".join(f"{c % 10}" for c in range(self.cols))]
        for r in range(self.rows):
            row = []
            for c in range(self.cols):
                cell = (r, c)
                ch = self.grid[r][c]
                if cell == self.last_signal:
                    ch = "L"
                if cell == self.oasis:
                    ch = "O"
                if cell == self.base:
                    ch = "B"
                if reveal and cell in self.storms:
                    ch = "S"
                if reveal and cell == self.hiker:
                    ch = "H"
                ch = marks.get(cell, ch)
                row.append(ch)
            lines.append(f"{r:>3} " + "".join(row))
        return "\n".join(lines)

    # ------------------------------------------------------------------ builders
    @classmethod
    def from_strings(cls, lines: List[str]) -> "DesertMap":
        """Build a small map by hand (used by the tests).

        Extra letters: B base, O oasis, L last signal, S sandstorm, H hiker.
        Letters stand on sand.
        """
        grid, storms = [], []
        base = oasis = hiker = last = None
        for r, line in enumerate(lines):
            row = []
            for c, ch in enumerate(line):
                if ch == "B":
                    base = (r, c)
                elif ch == "O":
                    oasis = (r, c)
                elif ch == "L":
                    last = (r, c)
                elif ch == "S":
                    storms.append((r, c))
                elif ch == "H":
                    hiker = (r, c)
                row.append(ch if ch in TERRAIN_NAME else SAND)
            grid.append("".join(row))
        if base is None:
            raise ValueError("map needs a base 'B'")
        return cls(grid, base, oasis if oasis else base, storms, hiker, last)

    @classmethod
    def generate(cls, seed: int, rows: int = 14, cols: int = 22, n_storms: int = 6) -> "DesertMap":
        """Your personal map. The seed is your student ID, so every student gets
        a different desert, a different hiker position and different storms."""
        rng = random.Random(seed)
        grid = [[SAND] * cols for _ in range(rows)]

        def walk(kind: str, n_walks: int, length: Tuple[int, int]):
            for _ in range(n_walks):
                r, c = rng.randrange(rows), rng.randrange(cols)
                for _ in range(rng.randint(*length)):
                    grid[r][c] = kind
                    dr, dc = rng.choice(MOVES)
                    r = min(max(r + dr, 0), rows - 1)
                    c = min(max(c + dc, 0), cols - 1)

        walk(DUNE, 6, (12, 26))
        walk(ROCK, 5, (6, 14))
        walk(MOUNTAIN, 6, (4, 9))

        # Base: somewhere on the left edge. Clear the cells around it.
        base = (rng.randrange(1, rows - 1), 0)
        for dr in (-1, 0, 1):
            for dc in (0, 1):
                grid[base[0] + dr][base[1] + dc] = SAND

        # Keep only the part of the desert the drone can reach from base.
        reach, stack = {base}, [base]
        while stack:
            r, c = stack.pop()
            for dr, dc in MOVES:
                n = (r + dr, c + dc)
                if 0 <= n[0] < rows and 0 <= n[1] < cols and n not in reach \
                        and grid[n[0]][n[1]] != MOUNTAIN:
                    reach.add(n)
                    stack.append(n)
        for r in range(rows):
            for c in range(cols):
                if (r, c) not in reach:
                    grid[r][c] = MOUNTAIN

        def dist(a: Cell, b: Cell) -> int:
            return abs(a[0] - b[0]) + abs(a[1] - b[1])

        open_cells = sorted(reach)
        far = [x for x in open_cells if dist(x, base) >= cols // 2 + 2] or open_cells
        last_signal = rng.choice(far)
        mid = [x for x in open_cells if 6 <= dist(x, base) and 6 <= dist(x, last_signal)]
        oasis = rng.choice(mid or open_cells)

        world = cls(["".join(row) for row in grid], base, oasis, (), None, last_signal, seed)

        # Hiker: drawn from the prior, so the prior is an honest belief.
        prior = world.hiker_prior()
        candidates = [x for x in open_cells if x not in (base, oasis)]
        hiker = rng.choices(candidates, weights=[prior[x] for x in candidates])[0]

        # Sandstorms: half near the search area, half anywhere.
        forbidden = {base, oasis, hiker, *world.neighbors(base)}
        pool = [x for x in open_cells if x not in forbidden]
        near = [x for x in pool if dist(x, last_signal) <= 6]
        storms = set()
        for group, k in ((near, n_storms // 2), (pool, n_storms - n_storms // 2)):
            group = [x for x in group if x not in storms]
            storms.update(rng.sample(group, min(k, len(group))))

        world.storms = frozenset(storms)
        world.hiker = hiker
        return world


def seed_from_student_id(student_id: str) -> int:
    """Turn a student ID such as '123456' into the map seed."""
    digits = "".join(ch for ch in str(student_id) if ch.isdigit())
    if not digits:
        raise ValueError("Student ID must contain digits, e.g. --id 123456")
    return int(digits)
